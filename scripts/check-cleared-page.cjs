// Uses an existing Playwright install; no dependency is added to the site.
// PLAYWRIGHT_MODULE=/path/to/playwright node scripts/check-cleared-page.cjs
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.CLEARED_BASE_URL || 'http://localhost:3000'
const artifacts = process.env.CLEARED_SCREENSHOTS || path.join(os.tmpdir(), 'cleared-updated-review')

;(async () => {
  fs.mkdirSync(artifacts, { recursive: true })
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    const failures = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', response => {
      if (response.url().startsWith(base) && response.status() >= 400) failures.push(`${response.status()} ${response.url()}`)
    })
    await page.goto(`${base}/project/cleared`)
    await page.getByRole('heading', { level: 1, name: /AI-assisted planning/ }).waitFor()
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.locator('video').count(), 7, 'Hero and feature sections contain seven focused walkthroughs')
    const heroVideo = page.locator('video').first()
    await heroVideo.scrollIntoViewIfNeeded()
    await page.waitForFunction(() => { const v = document.querySelector('video'); return !v.paused && v.readyState >= 2 })
    await page.getByRole('button', { name: /^Pause demo: Preview:/ }).click()
    await page.evaluate(() => document.querySelector('video').dispatchEvent(new Event('canplay')))
    await page.waitForTimeout(200)
    assert(await heroVideo.evaluate(v => v.paused), 'Manual pause must survive media readiness events')
    await page.getByRole('button', { name: /^Play demo: Preview:/ }).click()
    await page.waitForFunction(() => !document.querySelector('video').paused)
    await page.evaluate(() => scrollTo(0, 0))
    await page.screenshot({ path: path.join(artifacts, 'desktop-hero.png') })

    for (let index = 1; index < 4; index += 1) {
      const video = page.locator('video').nth(index)
      await video.scrollIntoViewIfNeeded()
      await page.waitForFunction(i => { const v = document.querySelectorAll('video')[i]; return v.readyState >= 2 && !v.paused }, index)
      assert.deepEqual(await video.evaluate(v => [v.videoWidth, v.videoHeight, v.loop, v.muted, v.controls]), [1468, 918, true, true, false])
    }
    await page.locator('#experience').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(artifacts, 'desktop-decisions.png') })
    await page.locator('#mobile-ui').scrollIntoViewIfNeeded()
    assert.equal(await page.locator('#mobile-ui img[src*="/phone"]').count(), 6, 'Restore all six mobile high-fidelity screens')
    assert(await page.locator('#mobile-ui details').evaluate(el => el.open), 'Mobile screens are visible by default')
    await page.screenshot({ path: path.join(artifacts, 'desktop-mobile-ui.png'), fullPage: false })
    await page.locator('#trust').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(artifacts, 'desktop-trust.png') })
    await page.locator('#prototype').scrollIntoViewIfNeeded()
    await page.waitForFunction(() => document.querySelectorAll('iframe').length === 1)
    const embeddedPrototype = page.frameLocator('iframe[title^="Google Calendar concept"]')
    await embeddedPrototype.getByText('Review next', { exact: true }).waitFor({ timeout: 20000 })
    await embeddedPrototype.getByText('Review next', { exact: true }).click()
    await embeddedPrototype.getByText('INFERRED', { exact: true }).waitFor()
    const prototypeLink = page.locator('#prototype').getByRole('link', { name: /^Open desktop prototype/ })
    assert.equal(await prototypeLink.getAttribute('target'), '_blank')
    const prototypeResponse = await page.request.get(new URL(await prototypeLink.getAttribute('href'), base).href)
    assert.equal(prototypeResponse.status(), 200, 'The desktop prototype is also available at full size')
    await page.screenshot({ path: path.join(artifacts, 'desktop-prototype.png') })
    assert(await page.locator('details video').evaluateAll(items => items.every(v => !v.getAttribute('src'))), 'Collapsed recordings should not load video')
    const moreInteractions = page.getByText('Explore three more desktop interactions', { exact: true })
    await moreInteractions.click()
    assert.equal(await page.locator('details video').count(), 3)
    for (let index = 4; index < 7; index += 1) {
      const video = page.locator('video').nth(index)
      await video.scrollIntoViewIfNeeded()
      await page.waitForFunction(i => { const v = document.querySelectorAll('video')[i]; return v.readyState >= 2 && !v.paused }, index)
      assert.deepEqual(await video.evaluate(v => [v.videoWidth, v.videoHeight, v.loop, v.muted, v.controls]), [1468, 918, true, true, false])
    }
    await moreInteractions.click()
    await page.waitForFunction(() => [...document.querySelectorAll('details video')].every(v => v.paused))
    assert(await page.locator('details video').evaluateAll(items => items.every(v => v.paused)), 'Collapsed recordings should pause')

    await page.getByText('Concept · Usability tested · Simulated data', { exact: true }).waitFor()
    assert(await page.getByRole('heading', { name: "Clear actions, with a need to verify the AI's interpretation." }).isVisible())
    assert(await page.getByText('Four participants returned to the source email', { exact: false }).isVisible())

    for (const width of [320, 390, 768]) {
      await page.setViewportSize({ width, height: 844 })
      await page.goto(`${base}/project/cleared`)
      await page.getByRole('heading', { level: 1 }).waitFor()
      await page.evaluate(() => document.fonts.ready)
      assert.equal(await page.locator('iframe').count(), 0, 'The desktop-only prototype uses a linked preview on narrow screens')
      assert.equal(await page.locator('a[aria-label="Open the desktop Calendar prototype in a new tab"] img').count(), 1)
      assert.equal(await page.locator('img[src*="/phone"]').count(), 6, 'Mobile high-fidelity gallery remains available')
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No horizontal overflow at ${width}`)
      await page.screenshot({ path: path.join(artifacts, `mobile-${width}.png`) })
      await page.locator('#prototype').scrollIntoViewIfNeeded()
      await page.screenshot({ path: path.join(artifacts, `prototype-${width}.png`) })
      await page.getByText('Explore three more desktop interactions', { exact: true }).click()
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Expanded demos fit at ${width}`)
      await page.locator('#validation').scrollIntoViewIfNeeded()
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Evaluation fits at ${width}`)
    }

    await page.goto(`${base}/visual/project/cleared`)
    await page.getByRole('heading', { level: 1 }).waitFor()
    assert.equal(await page.getByRole('link', { name: 'All Projects', exact: true }).getAttribute('href'), '/visual')

    const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
    await reduced.goto(`${base}/project/cleared`)
    const still = reduced.locator('video').first()
    await still.scrollIntoViewIfNeeded()
    await reduced.waitForTimeout(500)
    assert.equal(await still.getAttribute('src'), null, 'Reduced motion must not preload or autoplay video')
    await reduced.getByRole('button', { name: /^Play demo: Preview:/ }).click()
    await reduced.waitForFunction(() => !document.querySelector('video').paused)
    await reduced.getByRole('button', { name: /^Pause demo: Preview:/ }).click()
    assert(await still.evaluate(v => v.paused))
    assert.deepEqual(errors, [], 'No runtime errors')
    assert.deepEqual(failures, [], 'No failed local assets')
    console.log('PASS: tested status and findings, mobile hero walkthrough, six mobile screens, six desktop feature loops, embedded prototype, reduced motion, responsive widths and both portfolio routes.')
    console.log(`Screenshots: ${artifacts}`)
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
